// Writes api/_blog-reserved.js: the slugs under /blog/ that already belong to a page of the site
// (the original blog posts), so the blog-publish API never creates a post on top of one.
// Runs as part of `npm run rebrand`; run it alone with `node scripts/blog-reserved.mjs`.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const pages = JSON.parse(fs.readFileSync(path.join(root, "content/pages.json"), "utf8"));
const redirects = JSON.parse(fs.readFileSync(path.join(root, "content/redirects.json"), "utf8"));
const slugs = new Set(["upload", "page", "feed"]);
for (const p of [...pages.map((x) => x.path), ...Object.keys(redirects)]) {
  const m = /^\/blog\/([^/]+)\/?$/.exec(p);
  if (m) slugs.add(m[1]);
}
const list = [...slugs].sort();
fs.writeFileSync(
  path.join(root, "api/_blog-reserved.js"),
  `// Generated by scripts/blog-reserved.mjs: slugs under /blog/ that are taken by existing pages.\nexport default ${JSON.stringify(list, null, 2)};\n`
);
console.log(`blog-reserved: ${list.length} slugs`);
