// Packs the built site (dist/) as a zip for classic web hosting (GoDaddy cPanel / Apache).
// Run after `npm run build`:  node scripts/godaddy-package.mjs [output.zip]
// 1. Copies dist/ to .cache/godaddy-package/ and removes the Vercel-only analytics scripts.
// 2. Writes an .htaccess with the 301 redirects from vercel.json, https/non-www canonicalisation,
//    the 404 page and cache headers for static assets.
// 3. Zips the result (default: ~/Desktop/yourtanzaniatrip-godaddy-<date>.zip).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = path.resolve(import.meta.dirname, '..');
const dist = path.join(root, 'dist');
const stage = path.join(root, '.cache', 'godaddy-package');
if (!fs.existsSync(path.join(dist, 'index.html'))) throw new Error('dist/index.html missing: run `npm run build` first');

const site = new URL(/site:\s*'([^']+)'/.exec(fs.readFileSync(path.join(root, 'astro.config.mjs'), 'utf8'))[1]);
const host = site.hostname;                       // canonical host, e.g. yourtanzaniatrip.com
const altHost = host.startsWith('www.') ? host.slice(4) : 'www.' + host;
const date = new Date().toISOString().slice(0, 10);
const out = path.resolve(process.argv[2] || path.join(os.homedir(), 'Desktop', `yourtanzaniatrip-godaddy-${date}.zip`));

// 1. Stage a copy without Vercel-specific scripts.
fs.rmSync(stage, { recursive: true, force: true });
fs.cpSync(dist, stage, { recursive: true, filter: p => path.basename(p) !== '.DS_Store' });
const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]);
let stripped = 0;
for (const file of walk(stage).filter(f => f.endsWith('.html'))) {
  const src = fs.readFileSync(file, 'utf8');
  const html = src.replace(/\s*<!-- Vercel[^>]*-->/g, '').replace(/\s*<script[^>]*src="\/_vercel\/[^"]*"[^>]*><\/script>/g, '');
  if (html !== src) { fs.writeFileSync(file, html); stripped++; }
}

// 2. .htaccess: vercel.json sources look like "/old-path{/}?" (optional trailing slash).
const vercel = JSON.parse(fs.readFileSync(path.join(root, 'vercel.json'), 'utf8'));
const escapeRegex = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const redirects = vercel.redirects.map(r => {
  const m = /^(.*?)(\{\/\}\?)?$/.exec(r.source);
  if (/[:*()]/.test(m[1])) throw new Error(`Unsupported redirect pattern: ${r.source}`);
  const code = r.statusCode || (r.permanent === false ? 302 : 301);
  return `RedirectMatch ${code} ^${escapeRegex(m[1])}${m[2] ? '/?' : ''}$ ${r.destination}`;
});
const htaccess = `# Your Tanzania Trip - Apache configuration for GoDaddy web hosting.
# Generated by scripts/godaddy-package.mjs on ${date}; do not edit by hand, re-run the script.
Options -Indexes
DirectoryIndex index.html
AddDefaultCharset UTF-8
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On
# Canonical address: ${site.origin}/ (https, ${host.startsWith('www.') ? 'with' : 'without'} www)
RewriteCond %{HTTPS} !=on [OR]
RewriteCond %{HTTP_HOST} ^${escapeRegex(altHost)}$ [NC]
RewriteRule ^(.*)$ ${site.origin}/$1 [L,R=301]
</IfModule>

# Old addresses (from vercel.json): ${redirects.length} permanent redirects
<IfModule mod_alias.c>
${redirects.join('\n')}
</IfModule>

# Caching: hashed build assets for a year, media for a month, HTML always revalidated
<IfModule mod_expires.c>
ExpiresActive On
ExpiresByType text/html "access plus 0 seconds"
ExpiresByType application/json "access plus 0 seconds"
ExpiresByType text/css "access plus 1 month"
ExpiresByType application/javascript "access plus 1 month"
ExpiresByType image/jpeg "access plus 1 month"
ExpiresByType image/png "access plus 1 month"
ExpiresByType image/webp "access plus 1 month"
ExpiresByType image/svg+xml "access plus 1 month"
ExpiresByType image/x-icon "access plus 1 month"
ExpiresByType video/mp4 "access plus 1 month"
ExpiresByType font/woff2 "access plus 1 year"
</IfModule>
<IfModule mod_headers.c>
<FilesMatch "\\.(html|json|xml|txt)$">
Header set Cache-Control "no-cache"
</FilesMatch>
<FilesMatch "^.*/_astro/.*$">
Header set Cache-Control "public, max-age=31536000, immutable"
</FilesMatch>
Header always set X-Content-Type-Options "nosniff"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
</IfModule>
<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json image/svg+xml
</IfModule>
`;
fs.writeFileSync(path.join(stage, '.htaccess'), htaccess);

// 3. Zip (relative paths, dotfiles included, no macOS metadata).
fs.rmSync(out, { force: true });
fs.mkdirSync(path.dirname(out), { recursive: true });
execFileSync('zip', ['-r', '-X', '-q', out, '.', '-x', '*.DS_Store'], { cwd: stage, stdio: 'inherit' });
const mb = (fs.statSync(out).size / 1048576).toFixed(0);
console.log(`godaddy-package: ${walk(stage).length} files, ${redirects.length} redirects, Vercel scripts removed from ${stripped} pages -> ${out} (${mb} MB)`);
